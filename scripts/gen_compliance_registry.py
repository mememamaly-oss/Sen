#!/usr/bin/env python3
"""P2-C (2026-10-31): regenerate src/lib/compliance-registry.json from the
single source of truth (burhan/compliance.py).

The registry is the platform's render source for compliance views; this
script is what CI's drift job runs — a stale hand-edited registry can never
ship because `git diff` after regeneration must be empty.

Usage: python3 scripts/gen_compliance_registry.py [--check]
  default : rewrite src/lib/compliance-registry.json in place
  --check : exit 0 if in sync, exit 1 with a diff summary if stale
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

OUT = ROOT / "src" / "lib" / "compliance-registry.json"
GENERATOR_NOTE = ("GENERATED by scripts/gen_compliance_registry.py from "
                  "burhan/compliance.py — do not edit by hand; CI verifies "
                  "parity and fails on drift.")


def build() -> str:
    from burhan.compliance import compliance_json
    reg = compliance_json()
    reg["_generator"] = GENERATOR_NOTE
    # exact serialization contract of the checked-in file: 2-space indent,
    # literal UTF-8 (no \\u escapes), trailing newline
    return json.dumps(reg, indent=2, ensure_ascii=False) + "\n"


def digest(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]


def main() -> int:
    fresh = build()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current == fresh:
            print(f"registry in sync (sha256:{digest(fresh)})")
            return 0
        print("registry STALE — regenerate with: "
              "python3 scripts/gen_compliance_registry.py")
        print(f"  checked-in: {len(current)} bytes sha256:{digest(current)}")
        print(f"  fresh     : {len(fresh)} bytes sha256:{digest(fresh)}")
        return 1
    OUT.write_text(fresh, encoding="utf-8")
    print(f"wrote {OUT} ({len(fresh)} bytes, sha256:{digest(fresh)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
