export type DictKey = keyof typeof DICT["ar"];

type I18nCtx = {
  locale: Locale;
  dir: "rtl" | "ltr";
  t: (key: DictKey) => string;
  setLocale: (l: Locale) => void;
  fmtDate: (iso: string | null | undefined, opts?: { time?: boolean }) => string;
  fmtNum: (n: number | null | undefined) => string;
  fmtBytes: (b: number | null | undefined) => string;
  fmtDuration: (sec: number | null | undefined) => string;
  relTime: (iso: string | null | undefined) => string;
};

const Ctx = createContext<I18nCtx | null>(null);

function pick(): Locale {
  if (typeof window === "undefined") return "ar";
  const saved = window.localStorage.getItem("sentinel.locale");
  return saved === "en" || saved === "ar" ? saved : "ar";
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("ar");

  useEffect(() => {
    setLocaleState(pick());
  }, []);

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    try {
      window.localStorage.setItem("sentinel.locale", l);
    } catch {
      /* private mode */
    }
  }, []);

  useEffect(() => {
    const dir = locale === "ar" ? "rtl" : "ltr";
    document.documentElement.setAttribute("dir", dir);
    document.documentElement.setAttribute("lang", locale);
  }, [locale]);

  const value = useMemo<I18nCtx>(() => {
    const t = (key: DictKey) => DICT[locale][key] ?? key;
    const dateLocale = locale === "ar" ? "ar-LY" : "en-GB";
    return {
      locale,
      dir: locale === "ar" ? "rtl" : "ltr",
      t,
      setLocale,
      fmtDate(iso, opts) {
        if (!iso) return "—";
        const d = new Date(iso);
        if (opts?.time === false) return d.toLocaleDateString(dateLocale, { dateStyle: "medium" });
        return d.toLocaleString(dateLocale, {
          dateStyle: "medium",
          timeStyle: "short",
          hour12: false,
        });
      },
      fmtNum(n) {
        if (n === null || n === undefined) return "—";
        return n.toLocaleString(dateLocale);
      },
      fmtBytes(b) {
        if (b === null || b === undefined) return "—";
        if (b < 1024) return `${b} B`;
        if (b < 1024 * 1024) return `${(b / 1024).toFixed(1)} KB`;
        return `${(b / 1024 / 1024).toFixed(2)} MB`;
      },
      fmtDuration(sec) {
        if (sec === null || sec === undefined) return "—";
        const unit = locale === "ar" ? { s: "ث", m: "د", h: "س" } : { s: "s", m: "m", h: "h" };
        if (sec < 60) return `${Math.round(sec)}${unit.s}`;
        if (sec < 3600) return `${Math.floor(sec / 60)}${unit.m} ${Math.round(sec % 60)}${unit.s}`;
        return `${Math.floor(sec / 3600)}${unit.h} ${Math.floor((sec % 3600) / 60)}${unit.m}`;
      },
      relTime(iso) {
        if (!iso) return "—";
        const diff = (Date.now() - new Date(iso).getTime()) / 1000;
        const justNow = locale === "ar" ? "الآن" : "now";
        if (Math.abs(diff) < 60) return justNow;
        const rtf = new Intl.RelativeTimeFormat(dateLocale, { numeric: "auto" });
        if (Math.abs(diff) < 3600) return rtf.format(-Math.round(diff / 60), "minute");
        if (Math.abs(diff) < 86400) return rtf.format(-Math.round(diff / 3600), "hour");
        return rtf.format(-Math.round(diff / 86400), "day");
      },
    };
  }, [locale, setLocale]);

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18nCtx {
  const v = useContext(Ctx);
  if (!v) throw new Error("useI18n outside I18nProvider");
  return v;
}
