"""SENTINEL v4.0.0 — Autonomous Security Reasoning Engine (Phase 62).

The scanners below this layer answer "is THIS input injectable". This engine
answers "WHAT SHOULD WE TEST NEXT, AND WHY" — the way a human pentester
reasons over an application model:

    this endpoint MINTS an object id,
    the id appears in the response,
    a DIFFERENT endpoint consumes the same id,
    a second identity exists in the app
    ->  hypothesis: the object is usable cross-identity
    ->  test it.

Hypotheses are generated by MATCHING PATTERNS over the Security Digital Twin
(twin.py) — never from hard-coded endpoint lists — which makes them
transferable across applications. The rule core is fully deterministic
(same twin, same hypotheses, same order); a local LLM can later be layered
on top to phrase or rank, but nothing in the security decision path depends
on it.

Every hypothesis carries:
  pattern        the rule that fired (stable id)
  premise        the reasoning chain in plain language (the WHY)
  chain          the twin nodes the deduction walked (auditable)
  test           the engine/attack that can prove or refute it
  plan           the Safe Attack Planner class of the test
  status         tested:verified | tested:refuted | untestable:<reason>

After the scan, the hypothesis ledger is the honest account of REASONING
coverage: not just "which endpoints we touched", but "which attack theories
we formed, proved, refuted, or could not test and why" (e.g. a cross-identity
hypothesis that stays untested because no second account was configured —
the exact 'Untested: requires Manager identity' enterprise answer).
"""
from __future__ import annotations

import hashlib

from .planner import classify_operation
from .twin import DigitalTwin, infer_entity

# ------------------------------------------------------------------ rule ids
R_CROSS_IDENTITY_OBJECT = "R-CROSS-IDENTITY-OBJECT"
R_TOKENLESS_WRITE = "R-TOKENLESS-WRITE"
R_WF_SKIP_STEP = "R-WF-SKIP-STEP"
R_WF_REPLAY_FINAL = "R-WF-REPLAY-FINAL"
R_WF_TAMPER_VALUE = "R-WF-TAMPER-VALUE"
R_WF_DECLARED_PRIVILEGE = "R-WF-DECLARED-PRIVILEGE"
R_WF_CROSS_STATE = "R-WF-CROSS-STATE"
R_ADMIN_SURFACE_LOW_ROLE = "R-ADMIN-SURFACE-LOW-ROLE"
R_SECRET_EXPOSURE = "R-SECRET-EXPOSURE"
R_ID_PARAM_UNTESTED = "R-ID-PARAM-UNTESTED"
# ---- v4.1.0 patterns (branching & state intelligence + new protocols)
R_WF_BRANCH_BYPASS = "R-WF-BRANCH-BYPASS"
R_WF_UNAUTHORIZED_BRANCH = "R-WF-UNAUTHORIZED-BRANCH"
R_WF_APPROVAL_BYPASS = "R-WF-APPROVAL-BYPASS"
R_WF_ROLLBACK_ABUSE = "R-WF-ROLLBACK-ABUSE"
R_GQL_BOLA = "R-GQL-BOLA"
R_GQL_MUTATION_AUTHZ = "R-GQL-MUTATION-AUTHZ"
R_WS_CROSS_USER = "R-WS-CROSS-USER"


def _hid(pattern: str, key: str) -> str:
    return "H-" + hashlib.sha1(f"{pattern}|{key}".encode()).hexdigest()[:10]


def _mk(pattern: str, key: str, premise: str, chain: list[str], test: str,
         status: str = "generated", *, source: str = "twin-pattern",
         preconditions: list | None = None, expected: str = "",
         safety: str = "", evidence: str = "") -> dict:
    """The v4.1.0 structured hypothesis record. Back-compatible keys
    (premise/chain/test/plan/status) are preserved; the structured fields
    (source/preconditions/expected_behavior/test_plan/safety_class/
    actual_result/verification/evidence/final_state/reason) carry the full
    lifecycle so a report can answer 'what did SENTINEL believe, why, what
    did it predict, what happened, and why is the verdict what it is'."""
    plan = classify_operation(key.split(" ")[1] if " " in key else key,
                              key.split(" ")[0] if " " in key else "GET")
    rec = {"id": _hid(pattern, key), "pattern": pattern, "surface": key,
           "premise": premise, "chain": chain, "test": test,
           "plan": plan["impact"], "status": status,
           # ---- v4.1.0 structured lifecycle
           "source": source,
           "preconditions": preconditions or [],
           "expected_behavior": expected or premise,
           "test_plan": test,
           "safety_class": safety or plan["impact"],
           "actual_result": "",
           "verification": "",
           "evidence": evidence,
           "final_state": "generated",
           "reason": ""}
    if status.startswith("untestable:"):
        rec["final_state"] = "UNTESTABLE"
        rec["reason"] = status.split(":", 1)[1]
    return rec


# ------------------------------------------------------------------ generator
def generate_hypotheses(twin: DigitalTwin, logic_active: bool = False) -> list[dict]:
    """All attack theories the twin supports, deterministic order. Zero I/O."""
    hyps: list[dict] = []

    identities = twin.by_kind("identity")
    roles = twin.by_kind("role")
    flows = twin.by_kind("workflow")
    surfaces = twin.by_kind("surface")

    # ---- R-CROSS-IDENTITY-OBJECT: minted+consumed object per workflow + another identity
    wf_nodes = {w.key: w for w in flows}
    for ent in twin.by_kind("entity"):
        by_wf: dict[str, dict[str, list]] = {}
        for e in twin.edges:
            if e.rel not in ("mints", "consumes") or e.dst != ent.id:
                continue
            step = twin.nodes.get(e.src)
            if step is None:
                continue
            owner_wf = next((w.key for w in flows if any(
                se.src == step.id and se.rel == "step_of"
                and twin.nodes.get(se.dst) is not None
                and twin.nodes[se.dst].key == w.key for se in twin.edges)), "")
            by_wf.setdefault(owner_wf, {}).setdefault(e.rel, []).append(step)
        for wf_key, groups in sorted(by_wf.items()):
            if not groups.get("mints") or not groups.get("consumes"):
                continue
            mint_key, cons_key = groups["mints"][0], groups["consumes"][-1]
            premise = (f"a step of {wf_key} mints {ent.label} objects, a later step "
                       f"consumes them by id, and {len(identities)} identities exist — "
                       "if ownership is not checked server-side, one identity can "
                       "execute another's object")
            chain = [wf_key, mint_key.key, ent.key, cons_key.key] + [i.key for i in identities[:3]]
            status = "generated"
            if len(identities) < 2:
                status = "untestable:requires_second_identity"
            hyps.append(_mk(R_CROSS_IDENTITY_OBJECT, cons_key.key, premise, chain,
                            "workflow cross-user attack battery (cross_user)", status))

    # ---- R-TOKENLESS-WRITE: write surface carrying no token parameter
    for s in surfaces:
        if s.attrs.get("op_class") != "WRITE":
            continue
        params = twin.neighbors(s.id, "carries")
        has_token = any((p.attrs.get("value_kind") == "token") or
                        any(w in p.key.lower() for w in ("csrf", "token", "nonce"))
                        for p in params)
        if has_token:
            continue
        premise = (f"{s.label} changes state and carries no anti-CSRF token — "
                   "a hostile origin may be able to forge this action against "
                   "an authenticated victim")
        hyps.append(_mk(R_TOKENLESS_WRITE, s.key, premise,
                        [s.key] + [p.key for p in params[:4]],
                        "csrf detector (cross-origin replay)", "generated"))

    # ---- workflow invariants (skip / replay / tamper / privilege / cross-state)
    for wf in flows:
        steps = sorted([n for n in twin.by_kind("workflow_step")
                        if any(e.src == n.id and e.rel == "step_of"
                               and twin.nodes.get(e.dst) is not None
                               and twin.nodes[e.dst].key == wf.key
                               for e in twin.edges)],
                       key=lambda n: n.attrs.get("index", 0))
        if len(steps) < 2:
            continue
        producer, final = steps[0], steps[-1]
        hyps.append(_mk(
            R_WF_SKIP_STEP, final.key,
            f"{producer.attrs.get('action')} precedes {final.attrs.get('action')} in "
            f"{wf.key} — if the server does not enforce the sequence, the final "
            "step can run without its mandatory predecessor",
            [wf.key, producer.key, final.key],
            "workflow attack battery (step_bypass)", "generated"))
        hyps.append(_mk(
            R_WF_REPLAY_FINAL, final.key,
            f"{final.attrs.get('action')} is the executing step of {wf.key} — if it "
            "is not idempotent, replaying it executes the same resource twice",
            [wf.key, final.key],
            "workflow attack battery (duplicate)", "generated"))
        amount_params = [p for p in twin.neighbors(final.id, "tested_as") or []
                         if any(w in p.key.lower() for w in ("amount", "qty", "price", "total"))]
        hyps.append(_mk(
            R_WF_TAMPER_VALUE, final.key,
            f"{final.attrs.get('action')} re-receives the value an earlier step "
            "approved — if execution re-trusts request data over the stored "
            "record, the approved value can be swapped",
            [wf.key, final.key],
            "workflow attack battery (value_tamper)", "generated"))
        for opt in (wf.attrs.get("declared_privileged_options") or [])[:2]:
            hyps.append(_mk(
                R_WF_DECLARED_PRIVILEGE, f"POST {wf.key}:{opt['value']}",
                f"the UI itself labels option {opt['value']} '{opt['label']}' as "
                "privileged — if the server does not check the role, a "
                "lower-privilege session can execute it",
                [wf.key, opt["value"]],
                "workflow attack battery (privilege)", "generated"))

    # ---- R-WF-CROSS-STATE: workflows with rollback/cancel paths (from the
    # engine's own form-level discovery — these surfaces live behind POST
    # landings no crawler ever sees, so the TWIN carries them)
    for wf in flows:
        rollbacks = wf.attrs.get("rollback_paths") or []
        if not rollbacks:
            continue
        steps = sorted([n for n in twin.by_kind("workflow_step")
                        if any(e.src == n.id and e.rel == "step_of"
                               and twin.nodes.get(e.dst) is not None
                               and twin.nodes[e.dst].key == wf.key
                               for e in twin.edges)],
                       key=lambda n: n.attrs.get("index", 0))
        if len(steps) < 2:
            continue
        hyps.append(_mk(
            R_WF_CROSS_STATE, steps[-1].key,
            f"{wf.key} exposes a rollback path ({', '.join(rollbacks[:2])}) — if the "
            "executing step does not check the object's state, a cancelled "
            "object can still be executed",
            [wf.key, rollbacks[0], steps[-1].key],
            "workflow attack battery (cross_state)", "generated"))

    # ---- R-ADMIN-SURFACE-LOW-ROLE: matrix says a low role reaches admin surface
    admin_edges = [e for e in twin.edges if e.rel == "gates"
                   and "admin" in (twin.nodes.get(e.dst).key.lower()
                                   if twin.nodes.get(e.dst) else "")]
    for e in admin_edges:
        src, dst = twin.nodes.get(e.src), twin.nodes.get(e.dst)
        if src is None or dst is None or src.key in ("admin", "administrator", "root"):
            continue
        if e.attrs.get("verdict") == "reachable":
            hyps.append(_mk(
                R_ADMIN_SURFACE_LOW_ROLE, dst.key,
                f"the access matrix shows role '{src.key}' reaching the admin "
                f"surface {dst.key} — if the body is the privileged view, this is "
                "vertical privilege escalation",
                [src.key, dst.key],
                "authz engine (vertical escalation battery)", "generated"))

    # ---- R-SECRET-EXPOSURE: secret nodes exist
    for sec in twin.by_kind("secret"):
        hyps.append(_mk(
            R_SECRET_EXPOSURE, sec.key,
            f"a {sec.attrs.get('cls', 'credential')}-class secret is exposed in a "
            "response — if valid, it grants the privilege it carries (values are "
            "masked and never verified destructively)",
            [sec.key],
            "secrets engine (fresh-fetch exposure verification)", "generated"))

    # ---- R-ID-PARAM-UNTESTED: identifier params on surfaces with skip reasons
    for s in surfaces:
        reasons = s.attrs.get("untested_reasons") or []
        if not reasons:
            continue
        params = [p for p in twin.neighbors(s.id, "carries")
                  if p.attrs.get("value_kind") in ("identifier", "numeric")
                  and infer_entity(p.key, s.key)]
        if not params:
            continue
        hyps.append(_mk(
            R_ID_PARAM_UNTESTED, s.key,
            f"{s.label} carries object-identifier parameters but was left "
            f"untested ({', '.join(reasons[:2])}) — an object-level authorization "
            "defect could be hiding on exactly this surface",
            [s.key] + [p.key for p in params[:3]],
            "requires the missing precondition (see reasons)",
            "untestable:" + (reasons[0] if reasons else "unknown")))

    # ---- v4.1.0: GraphQL hypotheses — generated ONLY when the twin carries
    # graphql_endpoint nodes (observed by the GraphQL engine). Never from a
    # guess that GraphQL might exist.
    for g in twin.by_kind("graphql_endpoint"):
        hyps.append(_mk(
            R_GQL_BOLA, g.key,
            f"{g.key} exposes GraphQL queries — if object-level authorization "
            "is not enforced per field resolver, one identity can read "
            "another's objects by id",
            [g.key], "graphql engine (BOLA probe with the second identity)",
            "generated",
            source="twin:graphql_endpoint node (observed)",
            preconditions=["second identity configured",
                           "id-bearing query in the schema"],
            expected="the low-identity query returns the primary identity's "
                     "object data"))
        hyps.append(_mk(
            R_GQL_MUTATION_AUTHZ, g.key,
            f"{g.key} exposes GraphQL mutations — if a mutation does not "
            "enforce its privilege, an unauthenticated or low-privilege "
            "caller can execute it",
            [g.key], "graphql engine (mutation authorization probe)",
            "generated",
            source="twin:graphql_endpoint node (observed)",
            preconditions=["schema readable (introspection)",
                           "--logic-active for state-changing probes"],
            expected="the mutation executes and returns data for a "
                     "non-privileged caller",
            safety="STATE_CHANGING"))
    # ---- v4.1.0: WebSocket hypotheses — only for observed ws_channel nodes
    for w in twin.by_kind("ws_channel"):
        hyps.append(_mk(
            R_WS_CROSS_USER, w.key,
            f"{w.key} is a live WebSocket channel — if channel membership is "
            "not enforced, an unauthorized listener receives other "
            "identities' data",
            [w.key], "websocket engine (marker listen)", "generated",
            source="twin:ws_channel node (observed)",
            preconditions=["identity markers configured",
                           "protocol understood (JSON messages)"],
            expected="an anonymous listener captures another identity's "
                     "marker in channel messages"))

    # ---- v4.1.0: branching & state hypotheses from the workflow graph
    # (branch_transfer / approval steps / rollback paths ride the workflow
    # node attrs from the v4.1.0 flow summary)
    for wf in flows:
        steps = sorted([n for n in twin.by_kind("workflow_step")
                        if any(e.src == n.id and e.rel == "step_of"
                               and twin.nodes.get(e.dst) is not None
                               and twin.nodes[e.dst].key == wf.key
                               for e in twin.edges)],
                       key=lambda n: n.attrs.get("index", 0))
        if len(steps) < 2:
            continue
        if wf.attrs.get("branch_transfer"):
            bt = wf.attrs["branch_transfer"]
            hyps.append(_mk(
                R_WF_BRANCH_BYPASS,
                f"POST {wf.key}:branch={bt.get('field', '')}",
                f"{wf.key} transfers the branch choice '{bt.get('field', '')}' "
                "from an earlier step to a later hidden field — if the branch "
                "condition is not enforced server-side, forging the value "
                "enters the branch without its condition step",
                [wf.key, str(bt)],
                "workflow attack battery (branch_bypass)", "generated",
                source="workflow graph: branch_transfer edge",
                preconditions=["branch-transfer pattern learned",
                               "non-default branch option"],
                expected="the object is minted/executed inside the branch "
                         "with the forged value"))
        for br in (wf.attrs.get("branches") or [])[:2]:
            if br.get("class") == "restricted":
                hyps.append(_mk(
                    R_WF_UNAUTHORIZED_BRANCH, f"POST {wf.key}:{br['value']}",
                    f"the UI declares branch {br['field']}={br['value']} "
                    f"'{br.get('label', '')}' restricted — if the restriction "
                    "is not enforced server-side, a lower-privilege session "
                    "can execute it",
                    [wf.key, br["value"]],
                    "workflow attack battery (unauthorized_branch)", "generated",
                    source="workflow graph: restricted branch option",
                    preconditions=["restriction-vocabulary branch",
                                   "branch functional for the primary identity",
                                   "lower-privilege session configured"],
                    expected="the low-privilege oracle shows the restricted "
                             "branch executed"))
        if wf.attrs.get("approval_step"):
            hyps.append(_mk(
                R_WF_APPROVAL_BYPASS, f"POST {wf.attrs['approval_step']}",
                f"{wf.key} gates execution behind an approval step "
                f"({wf.attrs['approval_step']}) — if the approved state is "
                "not enforced, the executor runs without it",
                [wf.key, wf.attrs["approval_step"]],
                "workflow attack battery (approval_bypass)", "generated",
                source="workflow graph: approval step",
                preconditions=["approve-vocabulary step before the executor"],
                expected="the never-approved object executes"))
        for rp in (wf.attrs.get("rollback_only_paths") or [])[:1]:
            hyps.append(_mk(
                R_WF_ROLLBACK_ABUSE, f"POST {rp}",
                f"{wf.key} exposes a rollback path ({rp}) — if rollback "
                "reopens values without re-approval, a rolled-back object "
                "executes with a tampered value",
                [wf.key, rp], "workflow attack battery (rollback_abuse)",
                "generated",
                source="workflow graph: rollback-vocabulary path",
                preconditions=["rollback-vocabulary form action",
                               "resource linkage"],
                expected="the rolled-back object executes carrying the "
                         "tampered canary"))

    # deterministic order: pattern, then surface
    return sorted(hyps, key=lambda h: (h["pattern"], h["surface"]))


# ------------------------------------------------------------------ resolver
def resolve_hypotheses(hyps: list[dict], findings: list[dict],
                       workflow_attack_log: list[dict] | None = None,
                       authz_stats: dict | None = None) -> list[dict]:
    """Match each generated hypothesis against what the scan actually did.

    A hypothesis becomes:
      tested:verified   its proving engine produced a matching finding/verdict
      tested:refuted    the engine ran and the manipulation was refused
      untestable:*      the precondition never materialized (kept, with reason)
    """
    attack_log = workflow_attack_log or []
    found_types = {f.get("type", "") for f in findings}
    verified_urls = {f.get("url", "").split("?")[0] for f in findings}

    def _surface_path(surface: str) -> str:
        """'step 3:POST /wf/transfer/confirm' -> '/wf/transfer/confirm'."""
        i = surface.find("POST ")
        if i >= 0:
            return surface[i + 5:].strip()
        return surface.split(" ", 1)[-1] if " " in surface else surface

    def _attack_ran(surface: str, names: tuple) -> str:
        """'verified' | 'refuted' | 'skipped' for attacks against this surface's
        flow; '' when the battery never ran on it."""
        path = _surface_path(surface)
        out = ""
        for a in attack_log:
            if a.get("attack") in names and path.startswith(a.get("flow", "\u0000")):
                if a.get("verdict") == "verified":
                    return "verified"
                if a.get("verdict") == "skipped":
                    out = "skipped"
                elif not out:
                    out = "refuted"
        return out

    for h in hyps:
        pattern, surface = h["pattern"], h["surface"]
        if h["status"].startswith("untestable"):
            continue

        def _set(h, status, final, reason, actual="", verification=""):
            """v4.1.0: every resolved hypothesis carries its final state,
            an explicit reason, and what actually happened."""
            h["status"] = status
            h["final_state"] = final
            h["reason"] = reason
            if actual:
                h["actual_result"] = actual
            if verification:
                h["verification"] = verification
            return h

        if pattern == R_TOKENLESS_WRITE:
            if any(f.get("type") == "csrf" and f.get("url", "").split("?")[0]
                   .endswith(surface.split(" ", 1)[1] if " " in surface else surface)
                   for f in findings):
                _set(h, "tested:verified", "VERIFIED",
                     "the csrf detector verified acceptance on this surface",
                     actual="cross-origin replay accepted",
                     verification="csrf detector: fresh-origin replay")
            else:
                _set(h, "tested:refuted", "REFUTED",
                     "the detector ran and the write was never accepted "
                     "cross-origin",
                     actual="no acceptance observed",
                     verification="csrf detector ran to completion")
        elif pattern in (R_WF_SKIP_STEP, R_WF_REPLAY_FINAL, R_WF_TAMPER_VALUE,
                         R_WF_DECLARED_PRIVILEGE, R_WF_CROSS_STATE,
                         R_WF_BRANCH_BYPASS, R_WF_UNAUTHORIZED_BRANCH,
                         R_WF_APPROVAL_BYPASS, R_WF_ROLLBACK_ABUSE):
            attack_name = {R_WF_SKIP_STEP: ("step_bypass",),
                           R_WF_REPLAY_FINAL: ("duplicate",),
                           R_WF_TAMPER_VALUE: ("value_tamper",),
                           R_WF_DECLARED_PRIVILEGE: ("privilege",),
                           R_WF_CROSS_STATE: ("cross_state",),
                           R_WF_BRANCH_BYPASS: ("branch_bypass",),
                           R_WF_UNAUTHORIZED_BRANCH: ("unauthorized_branch",),
                           R_WF_APPROVAL_BYPASS: ("approval_bypass",),
                           R_WF_ROLLBACK_ABUSE: ("rollback_abuse",)}[pattern]
            v = _attack_ran(surface, attack_name)
            if v == "verified":
                _set(h, "tested:verified", "VERIFIED",
                     "the attack battery proved the invariant broken on this "
                     "flow (state-oracle delta)",
                     actual="state oracle gained the executed/tampered line",
                     verification="oracle:workflow-state-delta")
            elif v == "refuted":
                _set(h, "tested:refuted", "REFUTED",
                     "the attack ran and the target held (no proof of impact)",
                     actual="manipulation refused or no oracle delta",
                     verification="state oracle unchanged")
            else:
                _set(h, "untestable:precondition_absent", "UNTESTABLE",
                     "the manipulation's observable precondition never "
                     "materialized on this flow")
        elif pattern == R_GQL_BOLA:
            if any(f.get("type") == "graphql_bola" and surface.endswith(
                    f.get("url", "").split("//", 1)[-1].split("/", 1)[-1]
                    if f.get("url") else "") or f.get("url") == surface
                    for f in findings):
                _set(h, "tested:verified", "VERIFIED",
                     "the low-identity query returned the primary identity's "
                     "object data (marker present)",
                     actual="cross-identity object read captured",
                     verification="graphql:response-verification")
            elif surface in verified_urls or any(
                    f.get("type") == "graphql_bola" for f in findings):
                _set(h, "tested:refuted", "REFUTED",
                     "cross-identity query refused or returned no "
                     "other-identity object")
            else:
                _set(h, "untestable:no_second_identity", "UNTESTABLE",
                     "required second identity unavailable")
        elif pattern == R_GQL_MUTATION_AUTHZ:
            if any(f.get("type") == "graphql_mutation_authorization"
                   for f in findings):
                _set(h, "tested:verified", "VERIFIED",
                     "a mutation executed without its required privilege",
                     actual="mutation returned data with no errors from a "
                            "non-privileged caller",
                     verification="graphql:response-verification")
            else:
                _set(h, "untestable:mutation_not_exercisable", "UNTESTABLE",
                     "the mutation could not be exercised by the available "
                     "caller (auth required / planner-gated / no schema)")
        elif pattern == R_WS_CROSS_USER:
            if any(f.get("type") in ("websocket_cross_user_access",
                                     "websocket_sensitive_data_exposure")
                   for f in findings):
                _set(h, "tested:verified", "VERIFIED",
                     "an unauthorized listener captured another identity's "
                     "markers/data on the channel",
                     actual="marker-bearing messages captured",
                     verification="websocket:message-verification")
            else:
                _set(h, "untestable:markers_or_protocol_unavailable", "UNTESTABLE",
                     "no identity markers captured (or protocol not "
                     "understood) within the listen budget")
        elif pattern == R_CROSS_IDENTITY_OBJECT:
            v = _attack_ran(surface, ("cross_user", "cross_object"))
            if v == "verified":
                _set(h, "tested:verified", "VERIFIED",
                     "identity B executed a workflow object minted by "
                     "identity A (owner's oracle gained the executed line)")
            elif v == "refuted":
                _set(h, "tested:refuted", "REFUTED",
                     "the second identity could not execute the owner's object")
            else:
                _set(h, "untestable:precondition_absent", "UNTESTABLE",
                     "the cross-identity precondition never materialized "
                     "(shared object visibility / second identity)")
        elif pattern == R_WF_CROSS_STATE:
            v = _attack_ran(surface, ("cross_state",))
            if v == "verified":
                _set(h, "tested:verified", "VERIFIED",
                     "a cancelled/rolled-back object was executed anyway "
                     "(state-oracle proof)")
            elif v == "refuted":
                _set(h, "tested:refuted", "REFUTED",
                     "the state machine protected the object from execution "
                     "after cancel/rollback")
            else:
                _set(h, "untestable:precondition_absent", "UNTESTABLE",
                     "no rollback/cancel path observed on this flow")
        elif pattern == R_ADMIN_SURFACE_LOW_ROLE:
            if "vertical_privilege_escalation" in found_types:
                _set(h, "tested:verified", "VERIFIED",
                     "the authz engine verified vertical escalation")
            elif (authz_stats or {}).get("ran"):
                _set(h, "tested:refuted", "REFUTED",
                     "the authz engine ran; the low-privilege replay did not "
                     "yield the privileged view")
            else:
                _set(h, "untestable:no_multi_user_config", "UNTESTABLE",
                     "required second identity unavailable")
        elif pattern == R_SECRET_EXPOSURE:
            if "credential_exposure" in found_types:
                _set(h, "tested:verified", "VERIFIED",
                     "a secret is exposed and the exposure reproduced on a "
                     "fresh fetch")
            else:
                _set(h, "tested:refuted", "REFUTED",
                     "no secret exposure reproduced on fresh fetch")
        elif pattern == R_ID_PARAM_UNTESTED:
            if surface in verified_urls:
                _set(h, "tested:verified", "VERIFIED",
                     "the surface was reached by a verified finding after all")
    return hyps


def hypothesis_summary(hyps: list[dict]) -> dict:
    """The reasoning-coverage account (feeds the twin + reports)."""
    verified = sum(1 for h in hyps if h["status"] == "tested:verified")
    refuted = sum(1 for h in hyps if h["status"] == "tested:refuted")
    untestable = [h for h in hyps if h["status"].startswith("untestable")]
    reasons: dict[str, int] = {}
    for h in untestable:
        reasons[h["status"]] = reasons.get(h["status"], 0) + 1
    return {"generated": len(hyps),
            "tested": verified + refuted,
            "tested_verified": verified,
            "verified": verified,
            "refuted": refuted,
            "untestable": len(untestable),
            "untestable_reasons": dict(sorted(reasons.items()))}
