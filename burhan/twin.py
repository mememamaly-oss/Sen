"""Burhan v4.0.0 — Security Digital Twin (Phase 60).

Everything before v4.0.0 produced LISTS: endpoints, findings, flows, matrix
rows. This module fuses them into ONE queryable knowledge graph — a digital
twin of the application's security plane. The twin is built from artifacts the
scan ALREADY produced (zero extra requests, fully deterministic), and answers
the questions a list cannot:

    WHO   identities and roles that were actually exercised
    WHAT  surfaces, the parameters they carry, the entities those name
    HOW   multi-step workflows, the objects they mint and consume,
          the states those objects live through
    WHO-CAN-WHAT   the authorization matrix as provable graph relations
    WHAT-WE-PROVED findings, tied to the exact surface/identity/workflow
          step that produced them — and the coverage account of what was
          NOT tested and why

Node kinds:
  identity  role  session  surface  parameter  entity  object  state
  workflow  workflow_step  action  finding  secret  hypothesis

Edge kinds:
  has_role  authenticated  exposes  carries  typed_as  gates
  mints     consumes   observes  step_of  transitions_to
  tested_as produced_finding  exposed_secret  declared_privilege

The graph is the substrate for the Autonomous Reasoning Engine (reasoning.py):
hypotheses are generated by MATCHING PATTERNS over this graph, not by
hard-coded endpoint lists — which is what makes them transferable across
applications.
"""
from __future__ import annotations

import hashlib
import re
import urllib.parse
from dataclasses import dataclass, field

# ------------------------------------------------------------------ vocabulary
ENTITY_VOCAB: dict[str, tuple[str, ...]] = {
    # entity type -> (parameter/path words that indicate it)
    "User":        ("user", "username", "member", "profile", "uid", "customer",
                    "person", "employee", "applicant"),
    "Account":     ("account", "acct", "iban", "wallet"),
    "Order":       ("order", "purchase", "basket", "cart", "shipment"),
    "Invoice":     ("invoice", "bill", "receipt"),
    "Payment":     ("payment", "pay", "checkout", "coupon", "voucher", "billing"),
    "Transaction": ("transaction", "transfer", "txn", "wire", "payout", "deposit"),
    "Document":    ("document", "doc", "file", "attachment", "report", "contract"),
    "Ticket":      ("ticket", "issue", "case", "request", "queue", "task"),
    "Message":     ("message", "mail", "email", "inbox", "comment", "post"),
    "Session":     ("session", "jsessionid", "csrf", "token"),
}

ACTION_WORDS = ("create", "add", "new", "submit", "update", "edit", "modify",
                "change", "delete", "remove", "drop", "cancel", "approve",
                "reject", "confirm", "execute", "send", "upload", "register",
                "login", "logout", "reset", "rollback", "revert", "publish",
                "transfer", "pay", "checkout", "place", "book", "subscribe")
READ_WORDS = ("view", "get", "list", "search", "show", "detail", "details",
              "index", "browse", "read", "fetch", "find", "export", "report")

STATIC_EXTS = (".js", ".css", ".png", ".jpg", ".jpeg", ".gif", ".svg", ".ico",
               ".woff", ".woff2", ".ttf", ".map")

GATE_STATUS = {401: "auth_required", 403: "forbidden", 404: "not_found",
               405: "method_not_allowed"}


def infer_entity(name: str, path: str = "") -> str:
    """Deterministic entity typing from a parameter/path name. camelCase and
    snake_case split into words first (orderId -> 'order id'), then longest
    whole-word vocabulary match wins (account_id -> Account, not User via
    'id' — 'id' alone is not in the vocabulary at all)."""
    best, best_len = "", 0
    name_norm = re.sub(r"(?<=[a-z])(?=[A-Z])", " ", name or "")
    hay = " ".join([name_norm.lower().replace("-", " ").replace("_", " "),
                    (path or "").lower()])
    for etype, words in ENTITY_VOCAB.items():
        for w in words:
            if re.search(rf"(?<!\w){re.escape(w)}(?!\w)", hay) and len(w) > best_len:
                best, best_len = etype, len(w)
    return best


def classify_action(url: str, method: str) -> str:
    """READ | WRITE | NAV — the operation class of a surface (planner input)."""
    path = (url.split("?")[0] or "").lower()
    if (method or "GET").upper() in ("POST", "PUT", "PATCH", "DELETE"):
        return "WRITE"
    if path.endswith(STATIC_EXTS):
        return "NAV"
    seg = [s for s in path.split("/") if s]
    if not seg:
        return "NAV"
    action_seg = seg[-1]
    for w in READ_WORDS:
        if re.search(rf"(?<!\w){re.escape(w)}(?!\w)", action_seg.replace("-", " ")):
            return "READ"
    return "READ"          # plain GET pages default to read-shaped


def _nid(prefix: str, key: str) -> str:
    return prefix + "-" + hashlib.sha1(key.encode()).hexdigest()[:10]


# ------------------------------------------------------------------ data model
@dataclass
class TwinNode:
    kind: str                 # node kind vocabulary above
    key: str                  # stable natural identity (url / role / name)
    label: str = ""
    attrs: dict = field(default_factory=dict)

    @property
    def id(self) -> str:
        return _nid(self.kind, self.key)


@dataclass
class TwinEdge:
    src: str                  # node id
    dst: str                  # node id
    rel: str                  # edge kind vocabulary above
    attrs: dict = field(default_factory=dict)


class DigitalTwin:
    """The application's security knowledge graph (deterministic, serializable)."""

    def __init__(self, target_url: str = ""):
        self.target = target_url
        self.nodes: dict[str, TwinNode] = {}
        self.edges: list[TwinEdge] = []

    # ---------------------------------------------------------------- build
    def add_node(self, kind: str, key: str, label: str = "", **attrs) -> TwinNode:
        n = TwinNode(kind, key, label or key, attrs)
        if n.id not in self.nodes:
            self.nodes[n.id] = n
        else:
            self.nodes[n.id].attrs.update({k: v for k, v in attrs.items()
                                           if v not in (None, "", [], {})})
        return self.nodes[n.id]

    def add_edge(self, src: TwinNode, dst: TwinNode, rel: str, **attrs) -> None:
        e = TwinEdge(src.id, dst.id, rel, attrs)
        if not any(x.src == e.src and x.dst == e.dst and x.rel == rel
                   for x in self.edges):
            self.edges.append(e)

    # ---------------------------------------------------------------- read
    def by_kind(self, kind: str) -> list[TwinNode]:
        return sorted((n for n in self.nodes.values() if n.kind == kind),
                      key=lambda n: n.key)

    def neighbors(self, node_id: str, rel: str = "") -> list[TwinNode]:
        out = []
        for e in self.edges:
            if e.src == node_id and (not rel or e.rel == rel):
                if e.dst in self.nodes:
                    out.append(self.nodes[e.dst])
            elif e.dst == node_id and (not rel or e.rel == rel):
                if e.src in self.nodes:
                    out.append(self.nodes[e.src])
        return out

    def find(self, kind: str, key: str) -> TwinNode | None:
        return self.nodes.get(_nid(kind, key))

    def paths(self, src_id: str, dst_id: str, max_depth: int = 4) -> list[list]:
        """All simple paths src -> dst up to max_depth (bounded BFS/DFS)."""
        results: list[list[TwinEdge]] = []

        def walk(cur: str, seen: set, trail: list):
            if len(trail) >= max_depth:
                return
            for e in self.edges:
                if e.src != cur or e.dst in seen:
                    continue
                if e.dst == dst_id:
                    results.append(trail + [e])
                else:
                    walk(e.dst, seen | {e.dst}, trail + [e])

        walk(src_id, {src_id}, [])
        return results

    # ---------------------------------------------------------------- stats
    def stats(self) -> dict:
        kinds: dict[str, int] = {}
        for n in self.nodes.values():
            kinds[n.kind] = kinds.get(n.kind, 0) + 1
        rels: dict[str, int] = {}
        for e in self.edges:
            rels[e.rel] = rels.get(e.rel, 0) + 1
        return {"nodes": len(self.nodes), "edges": len(self.edges),
                "node_kinds": dict(sorted(kinds.items())),
                "edge_kinds": dict(sorted(rels.items()))}

    def to_dict(self) -> dict:
        """Serializable projection for reports / the glass dashboard."""
        return {
            "target": self.target,
            "stats": self.stats(),
            "nodes": [{"id": n.id, "kind": n.kind, "label": n.label, **n.attrs}
                      for n in sorted(self.nodes.values(), key=lambda n: (n.kind, n.key))],
            "edges": [{"src": e.src, "dst": e.dst, "rel": e.rel, **e.attrs}
                      for e in self.edges],
        }

    # ------------------------------------------------ v4.1.0 provenance layer
    def annotate_provenance(self) -> None:
        """Twin 2.0 (Phase V41-07): EVERY node and edge carries an explicit
        belief status and provenance string — the twin can always answer
        'why does Burhan believe this?'. Kind-specific defaults are applied
        only where the builder did not set them explicitly; nothing inference-
        shaped is ever labeled 'observed'."""
        node_defaults = {
            "surface":      ("observed", "discovery: crawl/openapi/browser surface map"),
            "param":        ("observed", "discovery: form/query/body parameter extraction"),
            "identity":     ("observed", "authz: account login session"),
            "role":         ("observed", "authz: configured role of a logged-in account"),
            "workflow":     ("observed", "workflow: guided-walk cluster learning"),
            "workflow_step": ("observed", "workflow: guided-walk submission"),
            "secret":       ("observed", "secrets: response scan (masked)"),
            "hypothesis":   ("inferred", "reasoning: pattern match over the twin"),
            "entity":       ("inferred", "twin: parameter-name entity typing"),
            "object":       ("inferred", "twin: object-id shape in parameters/oracle lines"),
            "graphql_endpoint": ("observed", "graphql: endpoint discovery + introspection"),
            "ws_channel":   ("observed", "websocket: channel discovery + handshake"),
            "boundary":     ("observed", "boundary: registry of limits"),
            "api":          ("observed", "apintel: unified API inventory"),
        }
        edge_defaults = {
            "carries": ("observed", "parameter rides this surface's requests"),
            "mints": ("observed", "workflow walk: landing carries the fresh id"),
            "consumes": ("observed", "workflow walk: step submits the id"),
            "step_of": ("observed", "workflow walk: ordered chain membership"),
            "gates": ("observed", "authz matrix: role->surface access probe"),
            "generated_hypothesis": ("inferred", "reasoning pattern generated from the twin"),
            "typed_as": ("inferred", "parameter name matches the entity vocabulary"),
            "exposes": ("inferred", "param-intel data-object projection"),
            "speaks_protocol": ("observed", "endpoint speaks this protocol (verified)"),
            "bounded_by": ("observed", "boundary registry links this surface's limit"),
        }
        for n in self.nodes.values():
            if "belief" not in n.attrs:
                b, p = node_defaults.get(n.kind, ("unknown", "unknown source"))
                n.attrs["belief"], n.attrs["provenance"] = b, p
            elif "provenance" not in n.attrs:
                n.attrs["provenance"] = "builder (explicit belief, default provenance)"
        for e in self.edges:
            if "belief" not in e.attrs:
                b, p = edge_defaults.get(e.rel, ("unknown", "unknown source"))
                e.attrs["belief"], e.attrs["provenance"] = b, p

    def belief_audit(self) -> list[str]:
        """The Twin 2.0 invariant check (consumed by the no-hallucination
        gate): every node and edge must carry both a belief status and a
        provenance string. Returns a list of violations (empty = clean)."""
        problems = []
        valid = {"observed", "inferred", "verified", "refuted", "unknown"}
        for n in self.nodes.values():
            if "belief" not in n.attrs or "provenance" not in n.attrs:
                problems.append(f"node {n.id} ({n.kind}) lacks belief/provenance")
            elif n.attrs.get("belief") not in valid:
                problems.append(f"node {n.id} has unknown belief "
                                f"'{n.attrs.get('belief')}'")
        for e in self.edges:
            if "belief" not in e.attrs or "provenance" not in e.attrs:
                problems.append(f"edge {e.src} -{e.rel}-> {e.dst} lacks "
                                "belief/provenance")
            elif e.attrs.get("belief") not in valid:
                problems.append(f"edge {e.rel} has unknown belief "
                                f"'{e.attrs.get('belief')}'")
        return problems

    def why(self, node_key_or_id: str) -> dict:
        """The auditor's question, answered: WHY does Burhan believe this
        node exists / holds this property? Returns the node's belief status,
        provenance, attributes, and the edges that connect it (with their own
        provenance). Never invents — reads only what the twin carries."""
        n = self.nodes.get(node_key_or_id) or \
            next((x for x in self.nodes.values()
                  if x.key == node_key_or_id or x.id == node_key_or_id), None)
        if n is None:
            return {"found": False, "query": node_key_or_id,
                    "answer": "no such node in the twin"}
        related = [{"rel": e.rel, "other": (self.nodes.get(e.dst) or
                                            self.nodes.get(e.src) or TwinNode("?", "?")).key,
                    "belief": e.attrs.get("belief", ""),
                    "provenance": e.attrs.get("provenance", "")}
                   for e in self.edges if e.src == n.id or e.dst == n.id][:12]
        return {"found": True, "kind": n.kind, "key": n.key,
                "belief": n.attrs.get("belief", "unknown"),
                "provenance": n.attrs.get("provenance", ""),
                "attributes": {k: v for k, v in n.attrs.items()
                               if k not in ("belief", "provenance")},
                "relations": related}


# ------------------------------------------------------------------ builder
def build_twin(target_url: str, endpoints: list, param_profile: dict | None = None,
               authz_result: dict | None = None, auth_mode: str = "anonymous",
               workflow_stats: dict | None = None, findings: list | None = None,
               coverage_summary: dict | None = None, secrets_summary: dict | None = None,
               hypotheses: list | None = None) -> DigitalTwin:
    """Fuse every scan artifact into one Digital Twin. Zero network requests;
    deterministic ordering everywhere (sorted inputs, stable ids)."""
    twin = DigitalTwin(target_url)
    findings = findings or []

    # ---- identities & roles (from the authz engine's exercised sessions)
    roles_seen: set[str] = set()
    if authz_result and authz_result.get("stats"):
        for role in authz_result["stats"].get("roles", []):
            roles_seen.add(role)
    if auth_mode and auth_mode != "anonymous":
        m = re.search(r"multi-user\((.*)\)", auth_mode)
        if m:
            roles_seen |= {r.strip() for r in m.group(1).split(",") if r.strip()}
        elif not roles_seen:
            roles_seen.add("user")            # single authenticated principal
    if not roles_seen:
        roles_seen.add("anonymous")
    for role in sorted(roles_seen):
        twin.add_node("role", role, label=f"role:{role}")
    anon = twin.find("role", "anonymous")
    if anon is None and auth_mode == "anonymous":
        anon = twin.add_node("role", "anonymous", label="role:anonymous")
    # authz accounts -> identities carrying their role
    if authz_result and authz_result.get("accounts"):
        for acc in sorted(authz_result["accounts"], key=lambda a: a["name"]):
            ident = twin.add_node("identity", acc["name"],
                                  label=acc.get("username", acc["name"]),
                                  role=acc.get("role", "user"),
                                  marker=acc.get("marker", ""),
                                  object_id=acc.get("object_id", ""))
            role_n = twin.find("role", acc.get("role", "user")) or \
                twin.add_node("role", acc.get("role", "user"))
            twin.add_edge(ident, role_n, "has_role")
    elif auth_mode not in ("anonymous", ""):
        ident = twin.add_node("identity", "primary", label="primary-session",
                              role="user" if roles_seen == {"user"} else sorted(roles_seen)[0])
        twin.add_edge(ident, twin.find("role", ident.attrs.get("role", "user")),
                      "has_role")

    # ---- surfaces + parameters + entity typing
    data_objects = dict((param_profile or {}).get("data_objects") or {})
    for ep in sorted(endpoints, key=lambda e: (e.url, e.method or "GET")):
        path = urllib.parse.urlsplit(ep.url).path or "/"
        method = (ep.method or "GET").upper()
        surf = twin.add_node("surface", f"{method} {path}",
                             label=f"{method} {path}",
                             method=method, path=path, url=ep.url,
                             op_class=classify_action(ep.url, method),
                             source=getattr(getattr(ep, "source", None), "value", "seed"),
                             auth_context=getattr(ep, "auth_context", "anonymous"))
        if getattr(ep, "auth_context", "anonymous") != "anonymous":
            ident = twin.find("identity", "primary") or twin.add_node(
                "identity", "primary", label="primary-session")
            twin.add_edge(ident, surf, "authenticated")
        for p in sorted(ep.parameters, key=lambda p: p.name):
            pk = f"{method} {path}:{p.name}"
            pnode = twin.add_node("parameter", pk, label=p.name,
                                  location=str(getattr(p, "location", "query")),
                                  value_kind=str(getattr(p, "kind", "generic")),
                                  value_shape=(p.value or "")[:24])
            twin.add_edge(surf, pnode, "carries")
            etype = infer_entity(p.name, path)
            if etype:
                ent = twin.add_node("entity", etype, label=f"entity:{etype}")
                twin.add_edge(pnode, ent, "typed_as")

    # data-object relations (param intelligence): entity -> surfaces carrying it
    for obj_name, surfaces in sorted(data_objects.items()):
        etype = infer_entity(obj_name) or "Object"
        ent = twin.add_node("entity", etype, label=f"entity:{etype}")
        for surf_key in sorted(surfaces)[:10]:
            method_path = surf_key if " " in surf_key else f"GET {surf_key}"
            s = twin.find("surface", method_path)
            if s is not None:
                twin.add_edge(ent, s, "exposes", via=obj_name)

    # ---- authorization matrix: role x surface access verdicts
    # (matrix keys carry the authz engine's provenance prefixes: 'role:admin',
    # 'anon' — normalize to the twin's role node keys)
    matrix = (authz_result or {}).get("matrix") or {}
    for url, role_status in sorted(matrix.items()):
        path = urllib.parse.urlsplit(url).path or "/"
        for role, status in sorted(role_status.items()):
            role_key = ("anonymous" if role == "anon"
                        else role.removeprefix("role:"))
            surf = twin.find("surface", f"GET {path}") or \
                twin.add_node("surface", f"GET {path}", label=f"GET {path}", path=path,
                              op_class="READ")
            role_n = twin.find("role", role_key)
            if role_n is None:
                continue
            gate = GATE_STATUS.get(status, "reachable" if status == 200 else "blocked")
            twin.add_edge(role_n, surf, "gates", status=status, verdict=gate)

    # ---- workflows: steps, minted/consumed objects, states, oracle
    for flow in ((workflow_stats or {}).get("flows") or []):
        wf = twin.add_node("workflow", flow["cluster"], label=flow["cluster"],
                           entry=flow.get("entry", ""), oracle=flow.get("state_oracle", ""),
                           rollback_paths=list(flow.get("rollback_paths") or []),
                           # ---- v4.1.0 Workflow Graph 2.0 attrs (branching &
                           # state intelligence; consumed by the reasoning
                           # generator + reports)
                           branches=list(flow.get("branches") or []),
                           branch_transfer=dict(flow["branch_transfer"])
                           if flow.get("branch_transfer") else None,
                           approval_step=flow.get("approval_step"),
                           cancel_paths=list(flow.get("cancel_paths") or []),
                           rollback_only_paths=list(flow.get("rollback_only_paths") or []),
                           state_transitions=list(flow.get("state_transitions")
                                                  or [])[:8],
                           graph=flow.get("graph") or None)
        prev = None
        for i, step in enumerate(flow.get("steps", [])):
            sk = f"step {i + 1}:POST {step['action']}"
            st_n = twin.add_node("workflow_step", sk, label=step["action"],
                                 index=i + 1, action=step["action"], method="POST")
            twin.add_edge(st_n, wf, "step_of")
            if prev is not None:
                twin.add_edge(prev, st_n, "transitions_to")
            surf = twin.find("surface", f"POST {step['action']}")
            if surf is not None:
                twin.add_edge(st_n, surf, "tested_as")
            prev = st_n
        for rp in flow.get("resource_params", []):
            etype = infer_entity(rp, flow["cluster"]) or "Object"
            ent = twin.add_node("entity", etype, label=f"entity:{etype}")
            ent.attrs.setdefault("resource_param", rp)
            # producer steps mint, later steps consume (engine records order)
            steps = flow.get("steps", [])
            for j, s in enumerate(steps):
                sn = twin.find("workflow_step", f"step {j + 1}:POST {s['action']}")
                if sn is not None:
                    twin.add_edge(sn, ent, "mints" if j < len(steps) - 1 else "consumes",
                                  param=rp)
        markers = (flow.get("execution_markers") or {})
        for st_word in markers.get("gained", [])[:6]:
            st = twin.add_node("state", f"{flow['cluster']}:{st_word}",
                               label=st_word, observed="execution_gained")
            twin.add_edge(wf, st, "transitions_to")
        for opt in flow.get("privilege_declared_options", []):
            wf.attrs.setdefault("declared_privileged_options", []).append(
                {"field": opt["field"], "value": opt["value"], "label": opt["label"]})
            role_n = twin.find("role", "admin")
            if role_n is not None:
                twin.add_edge(wf, role_n, "declared_privilege",
                              option=opt["value"], label=opt["label"])

    # ---- findings attach to the surface that produced them
    for f in sorted(findings, key=lambda f: (f.get("type", ""), f.get("url", ""))):
        url = (f.get("url") or "").split("?")[0]
        path = urllib.parse.urlsplit(url).path or url
        method = (f.get("method") or "GET").upper()
        fn = twin.add_node("finding", f.get("id", path + f.get("type", "")),
                           label=f.get("type", "finding"),
                           type=f.get("type", ""), severity=f.get("severity", ""),
                           confidence=f.get("confidence", 0.0),
                           status=f.get("status", "verified"))
        surf = twin.find("surface", f"{method} {path}")
        if surf is None:
            surf = twin.add_node("surface", f"{method} {path}", label=f"{method} {path}",
                                 method=method, path=path)
        twin.add_edge(surf, fn, "produced_finding", parameter=f.get("parameter", ""))

    # ---- secrets (masked by construction — values never enter the twin)
    for cls, surfaces in sorted(((secrets_summary or {}).get("classes") or {}).items()) \
            if isinstance((secrets_summary or {}).get("classes"), dict) else []:
        for surl in surfaces[:6]:
            path = urllib.parse.urlsplit(surl).path or surl
            surf = twin.find("surface", f"GET {path}")
            sec = twin.add_node("secret", f"{cls}@{path}", label=f"secret:{cls}",
                                cls=cls, value="********")
            if surf is not None:
                twin.add_edge(surf, sec, "exposed_secret")

    # ---- coverage: untested surfaces carry the honest reason
    cov = coverage_summary or {}
    for rec in (cov.get("endpoints") or [])[:200]:
        path = urllib.parse.urlsplit(rec.get("url", "")).path or rec.get("url", "")
        surf = twin.find("surface", f"{rec.get('method', 'GET')} {path}")
        if surf is not None:
            if rec.get("skips"):
                surf.attrs["untested_reasons"] = list(rec["skips"])[:4]
            if rec.get("activity"):
                surf.attrs["tested_as"] = list(rec["activity"])[:4]

    # ---- hypotheses (from the reasoning engine, if it already ran)
    for h in hypotheses or []:
        hn = twin.add_node("hypothesis", h["id"], label=h["pattern"],
                           pattern=h["pattern"], premise=h.get("premise", ""),
                           status=h.get("status", "generated"),
                           test=h.get("test", ""))
        target_key = h.get("surface", "")
        surf = twin.find("surface", target_key) if target_key else None
        if surf is not None:
            twin.add_edge(surf, hn, "generated_hypothesis")

    # ---- v4.1.0 Twin 2.0: every node and edge leaves this builder with an
    # explicit belief status + provenance (the no-hallucination invariant)
    twin.annotate_provenance()
    return twin


# ------------------------------------------------------------------ projections
def authorization_matrix(twin: DigitalTwin) -> dict:
    """The provable role x surface access matrix as a compact projection
    (identity rows from the twin's gates edges; statuses verbatim)."""
    roles = sorted({n.key for n in twin.by_kind("role")})
    rows: dict[str, dict[str, list[str]]] = {r: {} for r in roles}
    for e in twin.edges:
        if e.rel != "gates":
            continue
        src = twin.nodes.get(e.src)
        dst = twin.nodes.get(e.dst)
        if src is None or dst is None:
            continue
        rows.setdefault(src.key, {}).setdefault(
            e.attrs.get("verdict", str(e.attrs.get("status", ""))), []).append(dst.key)
    return {r: {v: sorted(surfs) for v, surfs in sorted(verdicts.items())}
            for r, verdicts in sorted(rows.items()) if verdicts}


def entity_inventory(twin: DigitalTwin) -> list[dict]:
    """Entity Intelligence projection: every typed entity with the surfaces
    that carry its parameters and the workflow steps that mint/consume it."""
    out = []
    for ent in twin.by_kind("entity"):
        # parameters typed as this entity (typed_as edges end at the entity)
        typed_params = {e.src for e in twin.edges
                        if e.rel == "typed_as" and e.dst == ent.id}
        # surfaces CARRYING one of those parameters (surface -carries-> param)
        surfaces = {twin.nodes[e.src].key for e in twin.edges
                    if e.rel == "carries" and e.dst in typed_params
                    and twin.nodes.get(e.src) is not None}
        # plus the param-intel exposes projection (data objects)
        surfaces |= {n.key for n in twin.neighbors(ent.id, "exposes")}
        minted_by = sorted({twin.nodes[e.src].key for e in twin.edges
                            if e.rel == "mints" and e.dst == ent.id
                            and twin.nodes.get(e.src) is not None})
        consumed_by = sorted({twin.nodes[e.src].key for e in twin.edges
                              if e.rel == "consumes" and e.dst == ent.id
                              and twin.nodes.get(e.src) is not None})
        out.append({"entity": ent.key, "carried_by_params": len(typed_params),
                    "surfaces": sorted(surfaces)[:12], "minted_by_steps": minted_by[:8],
                    "consumed_by_steps": consumed_by[:8]})
    return out


def twin_summary(twin: DigitalTwin) -> dict:
    """The compact dashboard summary (counts + headline facts)."""
    s = twin.stats()
    surfaces = twin.by_kind("surface")
    writes = [n for n in surfaces if n.attrs.get("op_class") == "WRITE"]
    untested = [n for n in surfaces if n.attrs.get("untested_reasons")]
    flows = twin.by_kind("workflow")
    return {
        **s,
        "identities": len(twin.by_kind("identity")),
        "roles": len(twin.by_kind("role")),
        "surfaces_total": len(surfaces),
        "surfaces_write": len(writes),
        "surfaces_read": len([n for n in surfaces if n.attrs.get("op_class") == "READ"]),
        "entities": len(twin.by_kind("entity")),
        "workflow_steps": len(twin.by_kind("workflow_step")),
        "states_observed": len(twin.by_kind("state")),
        "findings_attached": len(twin.by_kind("finding")),
        "secrets_masked": len(twin.by_kind("secret")),
        "hypotheses": len(twin.by_kind("hypothesis")),
        "surfaces_with_untested_reasons": len(untested),
        "flows": [{"cluster": f.key,
                   "steps": len([n for n in twin.by_kind("workflow_step")
                                 if any(e.src == n.id and e.rel == "step_of"
                                        and twin.nodes.get(e.dst) is not None
                                        and twin.nodes[e.dst].key == f.key
                                        for e in twin.edges)]),
                   "oracle": f.attrs.get("oracle", "")} for f in flows],
    }
